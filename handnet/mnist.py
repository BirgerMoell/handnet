"""
A hand-written neural network for MNIST digit classification.
No training. No gradients. No labels. Every weight was drawn by hand.

Architecture
------------
  image 28x28
    -> fixed blur (3x3 conv, hand-set Gaussian)            smooths stroke-width variation
    -> L2 normalisation                                     ink amount should not matter
    -> Conv2d(1 -> 26, kernel 28x28, padding 2)             26 hand-drawn digit templates
       (each kernel is an ASCII-art drawing, blurred,       (2-3 writing styles per digit)
        mean-subtracted and L2-normalised, so the
        activation is a normalised cross-correlation)
    -> MaxPool over the 5x5 offsets                         tolerates +-2 px translation
    -> Maxout: 26 template scores -> 10 class scores        "best matching style of this digit"
    -> + hand-set per-class bias
    -> argmax

The "weights" are the ASCII drawings in TEMPLATES below. Everything else is a fixed,
parameter-free (or hand-set) operation. Zero labelled images were used to write them.
"""
